/* Rebuild public/images/launch-cloud.js from public/images/launch-cloud.jpg.
   The .js file is the same photo as a data URL so the launch cloud can be a WebGL
   texture when the single-file game is opened straight from disk (file://). */
const fs = require('fs');
const path = require('path');
const jpg = fs.readFileSync(path.join(__dirname, '../public/images/launch-cloud.jpg'));
const b64 = jpg.toString('base64');
const out = `/* Twilight launch photo as a data URL. Chrome blocks a file:// page from using launch-cloud.jpg as a WebGL texture. Regenerated by tools/launch-cloud-data.cjs. */\nwindow.LUNA_LAUNCH_CLOUD="data:image/jpeg;base64,${b64}";\n`;
const dest = path.join(__dirname, '../public/images/launch-cloud.js');
fs.writeFileSync(dest, out);
console.log('wrote', dest, out.length, 'bytes');
